// Промпт LLM-«клиента» симулятора диалогов: правила поведения поверх brief персоны.
// Потребитель — src/routes/admin-sim.ts (personaSystemPrompt).

// Язык, на котором персона ДОЛЖНА писать реплики (для мультиязычных прогонов).
// Ключ — первые 2 буквы BCP-47 кода (ko/zh/en); ru/неизвестный → русский по умолчанию.
const PERSONA_LANG_NAME: Record<string, string> = {
  en: "английском",
  ko: "корейском",
  zh: "китайском",
};

export function buildSimPersonaSystemPrompt(
  brief: string,
  doneToken: string,
  languageCode?: string,
): string {
  const langName = languageCode
    ? PERSONA_LANG_NAME[languageCode.slice(0, 2).toLowerCase()]
    : undefined;
  // Бриф персоны написан по-русски, поэтому без явного указания модель пишет
  // по-русски даже при выбранном языке клиента. Жёстко закрепляем язык вывода.
  const langRule = langName
    ? `- ВАЖНО: пиши ВСЕ свои реплики ТОЛЬКО на ${langName} языке, даже если бриф выше написан по-русски — это твой родной язык. Никогда не переходи на русский.\n`
    : "";
  return (
    `${brief}\n\n` +
    "ПРАВИЛА:\n" +
    langRule +
    "- Ты — КЛИЕНТ (покупатель услуги), а не сотрудник, оператор или бот обменника.\n" +
    "- Собеседник — это обменник (бот/оператор). НИКОГДА не отвечай от его лица: не называй " +
    "курсы и суммы выдачи, не предлагай условия, не выдавай реквизиты/адреса и не предлагай " +
    "варианты получения — ты только СПРАШИВАЕШЬ и реагируешь как клиент.\n" +
    "- Ты пишешь как реальный человек в мессенджере: коротко, по одной мысли за сообщение.\n" +
    "- Пиши ТОЛЬКО следующую реплику клиента, без кавычек и пояснений.\n" +
    "- Реагируй на ответ собеседника естественно, продвигай диалог к своей цели.\n" +
    `- Когда твой вопрос решён или диалог логически завершён — ответь ровно: ${doneToken}`
  );
}
