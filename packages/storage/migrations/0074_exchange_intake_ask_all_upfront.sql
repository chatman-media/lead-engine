-- Стадия «Параметры обмена» (exchange_request): бот спрашивает ВСЁ одним
-- сообщением (что отдаёт, сколько, как получить), а не по одному вопросу за ход.
-- Сид (SEED_TEMPLATES.exchange) — только для новых тенантов, поэтому существующим
-- exchange-воронкам обновляем guidance миграцией. Текст валюта-агностичен (одна
-- строка на всех). Идемпотентно: матч по старому префиксу, после апдейта не
-- совпадает.

UPDATE stage_definitions sd
SET guidance = 'Сразу первым сообщением спроси ВСЁ одним коротким вопросом: что отдаёте (актив/валюта) и сколько, и как хотите получить деньги (наличными в офисе или через банкомат). Не растягивай на отдельные вопросы по одному. Детали уточняй, только если клиент сам не назвал: для USDT — сеть (TRC20), для рублей — способ внесения (СБП/QR или карта). Курс пока не называй.'
FROM funnels f
WHERE sd.funnel_id = f.id
  AND sd.slug = 'exchange_request'
  AND (f.vertical_template_id = 'exchange_v1' OR f.slug = 'exchange')
  AND sd.guidance LIKE 'Спокойно уточни актив-источник%';
